async function loadAlerts() {

    try {

        const response =
            await apiRequest("/api/alerts/");


        alerts =
            extractList(response, "alerts");


        alerts.sort(
            (a, b) =>
                Number(b.id ?? 0) -
                Number(a.id ?? 0)
        );


        renderAlerts();

    } catch (error) {

        console.error(
            "Alert loading error:",
            error
        );


        const container =
            document.getElementById(
                "alertsContainer"
            );


        if (container) {

            container.innerHTML = `
                <div class="empty-state">

                    <h3>
                        Unable to load alerts
                    </h3>

                    <p>
                        ${escapeHtml(error.message)}
                    </p>

                    <button
                        class="btn"
                        onclick="loadAlerts()"
                    >
                        Retry
                    </button>

                </div>
            `;
        }
    }
}


