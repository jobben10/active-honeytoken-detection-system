        // ====================================================
        // LOAD ALERTS
        // ====================================================

        let alerts = [];

        try {

            const alertResponse =
                await apiRequest("/api/alerts/");

            alerts =
                extractList(
                    alertResponse,
                    "alerts"
                );

        } catch (error) {

            console.warn(
                "Alerts unavailable:",
                error
            );

        }


        // ====================================================
        // FIND RELATED ALERT
        // ====================================================

        const relatedAlert =
            alerts.find(
                alert =>
                    Number(alert.event_id) ===
                    Number(eventId)
            ) || null;


        // ====================================================
        // LOAD AUDIT TRAIL
        // ====================================================

        let auditLogs = [];

        try {

            const auditResponse =
                await apiRequest("/api/audit/");

            auditLogs =
                extractList(
                    auditResponse,
                    "audit"
                );

            // Some versions of the API return "logs"
            if (!auditLogs.length) {

                auditLogs =
                    extractList(
                        auditResponse,
                        "logs"
                    );

            }

        } catch (error) {

            console.warn(
                "Audit trail unavailable:",
                error
            );

        }


        // ====================================================
        // MATCH REAL AUDIT RECORDS
        // ====================================================

        const currentEventId =
            String(event.id ?? eventId);

        const currentTokenId =
            String(event.token_id ?? "");

        const currentAlertId =
            relatedAlert
                ? String(relatedAlert.id)
                : "";


        const relatedAudit =
            auditLogs.filter(log => {

                const resourceId =
                    String(
                        log.resource_id ?? ""
                    );


                const details =
                    log.details || {};


                const auditEventId =
                    String(
                        details.event_id ??
                        log.event_id ??
                        ""
                    );


                const auditAlertId =
                    String(
                        details.alert_id ??
                        log.alert_id ??
                        ""
                    );


                const auditTokenId =
                    String(
                        details.token_id ??
                        log.token_id ??
                        log.resource_id ??
                        ""
                    );


                return (

                    auditEventId ===
                    currentEventId

                    ||

                    (
                        currentAlertId &&
                        auditAlertId ===
                        currentAlertId
                    )

                    ||

                    (
                        currentTokenId &&
                        auditTokenId ===
                        currentTokenId &&
                        (
                            details.event_type ===
                            event.event_type

                            ||

                            log.action ===
                            "HONEYTOKEN_TRIGGERED"
                        )
                    )

                );

            });


        // ====================================================
        // EVENT DATA
        // ====================================================

        const risk =
            Number(
                event.risk_score ?? 0
            );


        const intelligence =
            event.ip_intelligence || {};


        const mitre =
            event.mitre_attack || {};


        const techniques =
            Array.isArray(
                mitre.techniques
            )
                ? mitre.techniques
                : [];


        // Detection reasons come from the
        // actual correlated alert.

        const reasons =
            relatedAlert &&
            Array.isArray(
                relatedAlert.detection_reasons
            )
                ? relatedAlert.detection_reasons
                : [];


        // ====================================================
        // DETECTION REASONS
        // ====================================================

        const reasonsHtml =
            reasons.length

                ? reasons.map(
                    reason => `
                        <li>
                            ${escapeHtml(reason)}
                        </li>
                    `
                ).join("")

                : `
                    <li>
                        No detection reasons recorded.
                    </li>
                `;


