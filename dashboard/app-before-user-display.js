async function investigateAlert(alertId) {

    const alert =
        alerts.find(
            item =>
                Number(item.id) ===
                Number(alertId)
        );


    if (!alert) {

        alert(
            "Alert could not be found."
        );

        return;
    }


    createInvestigationModal();


    const modal =
        document.getElementById(
            "alertInvestigationModal"
        );


    modal.style.display = "flex";


    const body =
        document.getElementById(
            "investigationBody"
        );


    body.innerHTML = `
        <div class="investigation-loading">

            <div class="investigation-spinner"></div>

            <h3>
                Loading incident evidence...
            </h3>

            <p>
                Correlating alert, event, token,
                IP intelligence and audit records.
            </p>

        </div>
    `;


    try {

        const eventId =
            alert.event_id;


        let event = null;

        if (eventId) {

            try {

                event =
                    await apiRequest(
                        `/api/events/${encodeURIComponent(eventId)}`
                    );

            } catch (error) {

                console.warn(
                    "Detailed event endpoint unavailable:",
                    error
                );


                event =
                    events.find(
                        item =>
                            Number(item.id) ===
                            Number(eventId)
                    ) || null;
            }
        }


        let token = null;

        if (alert.token_id) {

            try {

                token =
                    await apiRequest(
                        `/api/tokens/${encodeURIComponent(alert.token_id)}`
                    );

            } catch (error) {

                console.warn(
                    "Token detail endpoint unavailable:",
                    error
                );


                token =
                    honeytokens.find(
                        item =>
                            item.token_id ===
                            alert.token_id
                    ) || null;
            }
        }


        let audit = [];

        try {

            const auditResponse =
                await apiRequest(
                    "/api/audit/"
                );


            audit =
                extractList(
                    auditResponse,
                    "audit_logs"
                );

        } catch (error) {

            console.warn(
                "Audit endpoint unavailable:",
                error
            );
        }


        renderInvestigation(
            alert,
            event,
            token,
            audit
        );


    } catch (error) {

        body.innerHTML = `

            <div class="investigation-error">

                <h3>
                    Investigation failed
                </h3>

                <p>
                    ${escapeHtml(
                        error.message
                    )}
                </p>

            </div>
        `;
    }
}


