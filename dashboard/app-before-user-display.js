window.performDashboardLogin =
    async function (event) {

        event.preventDefault();

        const username =
            document.getElementById(
                "loginUsername"
            ).value.trim();

        const password =
            document.getElementById(
                "loginPassword"
            ).value;

        const errorBox =
            document.getElementById(
                "loginError"
            );

        errorBox.style.display =
            "none";

        try {

            const response =
                await fetch(
                    "http://127.0.0.1:8000/api/auth/login",
                    {
                        method: "POST",

                        headers: {
                            "Content-Type":
                                "application/x-www-form-urlencoded"
                        },

                        body:
                            new URLSearchParams({
                                username:
                                    username,

                                password:
                                    password
                            })
                    }
                );

            const data =
                await response.json();

            if (!response.ok) {

                throw new Error(
                    data.detail ||
                    "Invalid username or password"
                );
            }

            localStorage.setItem(
                "honeytoken_access_token",
                data.access_token
            );

            localStorage.setItem(
                "honeytoken_user",
                JSON.stringify(
                    data.user
                )
            );

            window.authToken =
                data.access_token;

            window.authUser =
                data.user;

            const login =
                document.getElementById(
                    "dashboardLoginScreen"
                );

            if (login) {
                login.remove();
            }

            location.reload();

        } catch (error) {

            errorBox.textContent =
                error.message;

            errorBox.style.display =
                "block";
        }
    };


