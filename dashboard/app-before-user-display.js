function renderInvestigationAudit(
    audit,
    alert,
    event
) {

    if (!audit || !audit.length) {

        return `

            <div class="investigation-empty">

                No audit records were returned.

            </div>
        `;
    }


    const alertId =
        String(alert.id);


    const eventId =
        String(event?.id ?? alert.event_id ?? "");


    const tokenId =
        String(alert.token_id ?? "");


    const relevant =
        audit.filter(log => {

            const resourceId =
                String(
                    log.resource_id ?? ""
                );


            const details =
                String(
                    log.details ?? ""
                );


            return (
                resourceId === alertId ||
                resourceId === eventId ||
                details.includes(tokenId)
            );

        });


    const records =
        relevant.length
            ? relevant
            : audit.slice(0, 10);


    return `

        <div class="audit-investigation-list">

            ${records.slice(0, 20).map(
                log => `

                    <div class="audit-investigation-item">

                        <div>

                            <strong>
                                ${escapeHtml(
                                    log.action ||
                                    "AUDIT EVENT"
                                )}
                            </strong>

                            <span>
                                ${escapeHtml(
                                    log.resource_type ||
                                    "-"
                                )}
                            </span>

                        </div>


                        <p>
                            ${escapeHtml(
                                formatAuditDetails(
                                    log.details
                                )
                            )}
                        </p>


                        <small>

                            ${
                                log.source_ip
                                    ? `IP: ${escapeHtml(log.source_ip)} â€¢ `
                                    : ""
                            }

                            ${formatDate(
                                log.timestamp
                            )}

                        </small>

                    </div>

                `
            ).join("")}

        </div>
    `;
}


