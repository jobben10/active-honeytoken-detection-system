function showPage(pageName) {

    const validPages = [
        "dashboard",
        "tokens",
        "events",
        "alerts",
        "analytics",
        "audit"
    ];

    if (!validPages.includes(pageName)) {
        pageName = "dashboard";
    }

    /*
     * Hide EVERY page.
     */
    validPages.forEach(name => {

        const page =
            document.getElementById(`${name}Page`);

        if (!page) {
            return;
        }

        page.classList.add("hidden");

        page.style.setProperty(
            "display",
            "none",
            "important"
        );
    });


    /*
     * Show ONLY selected page.
     */
    const target =
        document.getElementById(`${pageName}Page`);

    if (target) {

        target.classList.remove("hidden");

        target.style.setProperty(
            "display",
            "block",
            "important"
        );
    }


    /*
     * Sidebar active state.
     */
    document
        .querySelectorAll("[data-page]")
        .forEach(item => {

            item.classList.toggle(
                "active",
                item.dataset.page === pageName
            );

        });


    /*
     * Header.
     */
    const titles = {
        dashboard: "Security Operations Center",
        tokens: "Honeytokens",
        events: "Security Events",
        alerts: "Security Alerts",
        analytics: "Security Analytics",
        audit: "Audit Trail"
    };

    const descriptions = {
        dashboard:
            "Real-time monitoring of honeytoken activity and security events.",

        tokens:
            "Manage deployed honeytokens and protected documents.",

        events:
            "Review security events generated by honeytoken activity.",

        alerts:
            "Investigate, acknowledge and resolve security alerts.",

        analytics:
            "Detection trends, risk scoring and attack activity.",

        audit:
            "Security actions and forensic audit records."
    };

    const title =
        document.getElementById("pageTitle");

    const description =
        document.getElementById("pageDescription");

    if (title) {
        title.textContent =
            titles[pageName];
    }

    if (description) {
        description.textContent =
            descriptions[pageName];
    }


    /*
     * Load only the selected page.
     */
    setTimeout(async () => {

        try {

            if (pageName === "dashboard") {
                await refreshDashboard();
            }

            else if (pageName === "tokens") {
                await loadHoneytokens();
            }

            else if (pageName === "events") {
                await loadEvents();
            }

            else if (pageName === "alerts") {
                await loadAlerts();
                renderAlerts();
            }

            else if (
                pageName === "analytics" &&
                typeof loadPhase5Analytics === "function"
            ) {
                await loadPhase5Analytics();
            }

            else if (
                pageName === "audit" &&
                typeof loadPhase5Audit === "function"
            ) {
                await loadPhase5Audit();
            }

        } catch (error) {

            console.error(
                `Page loading error [${pageName}]:`,
                error
            );

        }

    }, 50);
}


