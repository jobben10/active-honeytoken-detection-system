window.auditTrailRecords = {};

window.loadPhase5Audit = async function () {

    const container =
        document.getElementById("phase5AuditList");

    if (!container) {
        return;
    }

    container.innerHTML = `
        <div class="loading-state">
            Loading audit records...
        </div>
    `;

    try {

        const response =
            await apiRequest("/api/audit/");

        let logs = [];

        if (Array.isArray(response)) {
            logs = response;
        } else if (Array.isArray(response.logs)) {
            logs = response.logs;
        } else if (Array.isArray(response.audit)) {
            logs = response.audit;
        } else if (Array.isArray(response.audit_logs)) {
            logs = response.audit_logs;
        }

        logs.sort(
            (a, b) =>
                Number(b.id || 0) -
                Number(a.id || 0)
        );

        window.auditTrailRecords = {};

        logs.forEach(function (log) {
            window.auditTrailRecords[
                String(log.id)
            ] = log;
        });

        if (!logs.length) {

            container.innerHTML = `
                <div class="empty-state">
                    No audit records found.
                </div>
            `;

            return;
        }

        let html = `

            <div class="table-wrapper">

                <table class="data-table">

                    <thead>
                        <tr>
                            <th>ID</th>
                            <th>Action</th>
                            <th>Resource</th>
                            <th>Resource ID</th>
                            <th>Source IP</th>
                            <th>Event</th>
                            <th>Risk</th>
                            <th>Severity</th>
                            <th>Timestamp</th>
                            <th>Actions</th>
                        </tr>
                    </thead>

                    <tbody>
        `;

        logs.forEach(function (log) {

            const details =
                log.details || {};

            const sourceIp =
                details.source_ip ||
                details.ip_address ||
                "-";

            const eventId =
                details.event_id ||
                "-";

            const risk =
                Number(
                    details.risk_score || 0
                );

            const severity =
                details.severity ||
                "-";

            let riskHtml = "-";

            if (risk > 0) {

                let riskClass = "low";

                if (risk >= 80) {
                    riskClass = "critical";
                } else if (risk >= 60) {
                    riskClass = "high";
                } else if (risk >= 30) {
                    riskClass = "medium";
                }

                riskHtml = `
                    <span class="risk-score ${riskClass}">
                        ${risk}/100
                    </span>
                `;
            }

            let severityHtml =
                escapeHtml(severity);

            if (
                typeof severityBadge ===
                "function"
            ) {
                severityHtml =
                    severityBadge(severity);
            }

            let timestamp =
                escapeHtml(
                    log.timestamp || "-"
                );

            if (
                typeof formatDate ===
                "function"
            ) {
                timestamp =
                    formatDate(
                        log.timestamp
                    );
            }

            html += `

                <tr>

                    <td>
                        ${escapeHtml(
                            log.id ?? "-"
                        )}
                    </td>

                    <td>
                        <strong>
                            ${escapeHtml(
                                log.action || "-"
                            )}
                        </strong>
                    </td>

                    <td>
                        ${escapeHtml(
                            log.resource_type || "-"
                        )}
                    </td>

                    <td>
                        <code>
                            ${escapeHtml(
                                log.resource_id || "-"
                            )}
                        </code>
                    </td>

                    <td>
                        ${escapeHtml(
                            sourceIp
                        )}
                    </td>

                    <td>
                        ${
                            eventId !== "-"
                                ? `<code>${escapeHtml(eventId)}</code>`
                                : "-"
                        }
                    </td>

                    <td>
                        ${riskHtml}
                    </td>

                    <td>
                        ${severityHtml}
                    </td>

                    <td>
                        ${timestamp}
                    </td>

                    <td>

                        <button
                            class="btn btn-sm"
                            onclick="showAuditRecord('${String(log.id)}')"
                            title="View audit record"
                        >
                            &#128269; View
                        </button>

                    </td>

                </tr>
            `;
        });

        html += `

                    </tbody>

                </table>

            </div>

            <div class="page-info">
                Showing
                <strong>${logs.length}</strong>
                audit records
            </div>
        `;

        container.innerHTML = html;

    } catch (error) {

        console.error(
            "Audit loading error:",
            error
        );

        container.innerHTML = `

            <div class="empty-state">

                <h3>
                    Unable to load audit records
                </h3>

                <p>
                    ${escapeHtml(
                        error.message ||
                        "Unknown error"
                    )}
                </p>

                <button
                    class="btn"
                    onclick="window.loadPhase5Audit()"
                >
                    Retry
                </button>

            </div>
        `;
    }
};


