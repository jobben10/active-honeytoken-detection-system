refreshCurrentPage = async function () {

    let pageName = "dashboard";

    const pageNames = [
        "dashboard",
        "tokens",
        "events",
        "alerts",
        "analytics",
        "audit"
    ];

    /*
     * Find the page that is actually visible.
     * This fixes the problem where navigation displays
     * Analytics/Audit without updating the URL hash.
     */

    for (const name of pageNames) {

        const page =
            document.getElementById(
                `${name}Page`
            );

        if (!page) {
            continue;
        }

        const style =
            window.getComputedStyle(page);

        const visible =
            style.display !== "none" &&
            !page.classList.contains("hidden");

        if (visible) {
            pageName = name;
            break;
        }
    }

    console.log(
        `[AUTO REFRESH] Refreshing visible page: ${pageName}`
    );

    try {

        if (pageName === "dashboard") {

            await refreshDashboard();

        }

        else if (pageName === "tokens") {

            await loadHoneytokens();

        }

        else if (pageName === "events") {

            await loadEvents();

        }

        else if (pageName === "alerts") {

            await loadAlerts();

        }

        else if (pageName === "analytics") {

            if (
                typeof loadPhase5Analytics ===
                "function"
            ) {

                await loadPhase5Analytics();

            }

        }

        else if (pageName === "audit") {

            if (
                typeof loadPhase5Audit ===
                "function"
            ) {

                await loadPhase5Audit();

            }

        }

    }

    catch (error) {

        console.error(
            `[AUTO REFRESH] ${pageName} failed:`,
            error
        );

    }

};

