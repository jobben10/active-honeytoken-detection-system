/*
 * Dashboard MITRE ATT&CK
 *
 * Gets MITRE information directly from events and,
 * when necessary, audit records.
 */
async function renderDashboardMitre() {

    const container =
        document.getElementById("mitreContainer");

    if (!container) {
        return;
    }

    try {

        const response =
            await apiRequest("/api/events/");

        const dashboardEvents =
            extractList(response, "events")
                .sort(
                    (a, b) =>
                        Number(b.id ?? 0) -
                        Number(a.id ?? 0)
                );

        const techniqueMap =
            new Map();


        /*
         * First source: security events.
         */
        for (const event of dashboardEvents) {

            const mitre =
                event?.mitre_attack;

            const techniques =
                Array.isArray(
                    mitre?.techniques
                )
                    ? mitre.techniques
                    : [];

            for (const technique of techniques) {

                const id =
                    technique?.id ||
                    technique?.technique ||
                    "";

                if (!id) {
                    continue;
                }

                techniqueMap.set(
                    id,
                    technique
                );
            }
        }


        /*
         * Second source: audit records.
         * This catches cases where MITRE was stored
         * in audit details rather than the event object.
         */
        if (!techniqueMap.size) {

            try {

                const auditResponse =
                    await apiRequest("/api/audit/");

                const logs =
                    extractList(
                        auditResponse,
                        "logs"
                    );

                for (const log of logs) {

                    let details =
                        log?.details || {};

                    if (
                        typeof details ===
                        "string"
                    ) {

                        try {

                            details =
                                JSON.parse(
                                    details
                                );

                        } catch {

                            details = {};

                        }
                    }

                    const mitre =
                        details?.mitre_attack;

                    const techniques =
                        Array.isArray(
                            mitre?.techniques
                        )
                            ? mitre.techniques
                            : [];

                    for (
                        const technique
                        of techniques
                    ) {

                        const id =
                            technique?.id ||
                            technique?.technique ||
                            "";

                        if (!id) {
                            continue;
                        }

                        techniqueMap.set(
                            id,
                            technique
                        );
                    }
                }

            } catch (auditError) {

                console.warn(
                    "Dashboard MITRE audit fallback failed:",
                    auditError
                );
            }
        }


        const techniques =
            Array.from(
                techniqueMap.values()
            );


        if (!techniques.length) {

            container.innerHTML = `
                <div class="empty-state">
                    No MITRE ATT&CK techniques recorded.
                </div>
            `;

            return;
        }


        container.innerHTML = `
            <div class="mitre-list">

                ${techniques.map(
                    technique => `

                    <div
                        class="mitre-item"
                        style="
                            padding:14px;
                            margin-bottom:10px;
                            border:1px solid #233149;
                            border-radius:8px;
                            background:#0d1522;
                        "
                    >

                        <div>

                            <strong
                                style="
                                    color:#60a5fa;
                                    margin-right:10px;
                                "
                            >
                                ${escapeHtml(
                                    technique.id ||
                                    "-"
                                )}
                            </strong>

                            <span>
                                ${escapeHtml(
                                    technique.technique ||
                                    technique.name ||
                                    "-"
                                )}
                            </span>

                        </div>

                        <small
                            style="
                                display:block;
                                margin-top:6px;
                                opacity:.65;
                            "
                        >
                            Tactic:
                            ${escapeHtml(
                                technique.tactic ||
                                "-"
                            )}
                        </small>

                    </div>

                `
                ).join("")}

            </div>
        `;
    

    } catch (error) {

        console.error(
            "Dashboard MITRE error:",
            error
        );

        container.innerHTML = `
            <div class="empty-state">
                Unable to load MITRE ATT&CK data.
            </div>
        `;
    }
}


