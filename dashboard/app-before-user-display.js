// ============================================================

function updateThreatLevel() {

    const scoreElement =
        document.getElementById(
            "threatScore"
        );


    const labelElement =
        document.getElementById(
            "threatLabel"
        );


    if (!scoreElement ||
        !labelElement) {

        return;
    }


    if (!events.length) {

        scoreElement.textContent = "0";

        labelElement.textContent =
            "LOW";

        labelElement.style.color =
            "#4ade80";

        return;
    }


    const scores =
        events.map(
            event =>
                Number(
                    event.risk_score ?? 0
                )
        );


    const highestRisk =
        Math.max(...scores);


    scoreElement.textContent =
        highestRisk;


    if (highestRisk >= 80) {

        labelElement.textContent =
            "CRITICAL";

        labelElement.style.color =
            "#f87171";

    } else if (highestRisk >= 60) {

        labelElement.textContent =
            "HIGH";

        labelElement.style.color =
            "#fb923c";

    } else if (highestRisk >= 30) {

        labelElement.textContent =
            "MEDIUM";

        labelElement.style.color =
            "#fbbf24";

    } else {

        labelElement.textContent =
            "LOW";

        labelElement.style.color =
            "#4ade80";
    }
}


