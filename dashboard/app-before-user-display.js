function setupNavigation() {

    const navItems =
        document.querySelectorAll(".nav-item, .nav-link");

    navItems.forEach(item => {

        item.addEventListener("click", () => {

            navItems.forEach(nav =>
                nav.classList.remove("active")
            );

            item.classList.add("active");
        });

    });
}


function showPage(pageName) {

    const pages = [
        "dashboard",
        "tokens",
        "events",
        "alerts"
    ];

    pages.forEach(name => {

        const page =
            document.getElementById(`${name}Page`);

        if (!page) {
            return;
        }

        if (name === pageName) {

            page.classList.remove("hidden");
            page.style.display = "block";

        } else {

            page.classList.add("hidden");
            page.style.display = "none";
        }
    });


    const titles = {
        dashboard: "Security Operations Center",
        tokens: "Honeytokens",
        events: "Security Events",
        alerts: "Security Alerts"
    };


    const descriptions = {
        dashboard:
            "Real-time monitoring of honeytoken activity and security events.",

        tokens:
            "Manage deployed honeytokens and protected documents.",

        events:
            "Review security events generated by honeytoken activity.",

        alerts:
            "Investigate, acknowledge and resolve security alerts."
    };


    const title =
        document.getElementById("pageTitle");

    const description =
        document.getElementById("pageDescription");


    if (title) {
        title.textContent =
            titles[pageName] || titles.dashboard;
    }


    if (description) {
        description.textContent =
            descriptions[pageName] || "";
    }


    document
        .querySelectorAll("[data-page]")
        .forEach(item => {

            item.classList.toggle(
                "active",
                item.dataset.page === pageName
            );

        });


    if (pageName === "dashboard") {
        loadDashboard();
    }

    if (pageName === "tokens") {
        loadHoneytokens();
    }

    if (pageName === "events") {
        loadEvents();
    }

    if (pageName === "alerts") {
        loadAlerts();
    }
}


