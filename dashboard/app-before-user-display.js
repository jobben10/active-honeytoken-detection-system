const originalLoadEvents = loadEvents;

loadEvents = async function() {

    await originalLoadEvents();

    /*
     * Rebuild the latest intelligence after the original
     * event-loading process has completed.
     */

    if (
        typeof events !== "undefined" &&
        Array.isArray(events) &&
        events.length > 0
    ) {

        const publicEvent = events.find(event => {

            const ip =
                String(
                    event?.source_ip ||
                    ""
                ).trim();

            const intel =
                event?.ip_intelligence;

            if (!ip || !intel) {
                return false;
            }

            const privateIp =
                ip.startsWith("10.") ||
                ip.startsWith("192.168.") ||
                /^172\.(1[6-9]|2[0-9]|3[0-1])\./.test(ip) ||
                ip === "127.0.0.1" ||
                ip.toLowerCase() === "localhost";

            return (
                !privateIp &&
                Object.keys(intel).length > 0
            );
        });

        renderLatestIntelligence(
            publicEvent || events[0]
        );
    }
};


