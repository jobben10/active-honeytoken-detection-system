function updateAnalytics() {

    const scores =
        events.map(
            event =>
                Number(
                    event.risk_score ?? 0
                )
        );


    const totalRisk =
        scores.reduce(
            (sum, value) =>
                sum + value,
            0
        );


    const averageRisk =
        scores.length
            ? Math.round(
                totalRisk /
                scores.length
            )
            : 0;


    setText(
        "analyticsRisk",
        totalRisk
    );


    setText(
        "averageRisk",
        averageRisk
    );
}


